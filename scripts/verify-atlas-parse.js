/* Offline verification: run processed/*.json through Phaser 3.90's OWN atlas
 * parser source (no DOM/browser required) and assert the frames that the
 * TextureManager.addAtlas() dispatch would actually create in the browser.
 *
 * Dispatch mirror (TextureManager.js:824):
 *   Array.isArray(data.frames) -> addAtlasJSONArray -> Parsers.JSONArray
 *   otherwise                  -> addAtlasJSONHash  -> Parsers.JSONHash (warns
 *                                 "missing 'frames' Object", adds ZERO frames)
 *
 * Usage: node scripts/verify-atlas-parse.js   (exit 0 = pass)
 */
const fs = require("fs");
const path = require("path");

// Relative require (bypasses package "exports" restrictions on bare subpaths).
const JSONArray = require("../node_modules/phaser/src/textures/parsers/JSONArray");

const OUT = path.join(__dirname, "..", "public", "assets", "mailxp", "processed");

const COUNTS = {
  "office-props.json": 21,
  "mail-effects.json": 14,
  "office-npcs.json": 16,
  "ai-workers.json": 8,
  "mail-bird.json": 8,
};

const SPOT = {
  "office-props.json": ["desk", "couch", "plant", "draftcoin"],
  "mail-effects.json": ["mail-closed", "reward-token", "levelup-burst"],
  "office-npcs.json": ["officer-down", "monkey-up", "intern-left"],
  "ai-workers.json": ["understanding-front", "response-back"],
  "mail-bird.json": ["right-0", "left-3"],
};

/** Exact dispatch logic from Phaser 3.90 TextureManager.addAtlas(). */
function dispatch(data) {
  return Array.isArray(data.textures) || Array.isArray(data.frames) ? "JSONArray" : "JSONHash";
}

/** Minimal Texture stand-in covering what Parsers.JSONArray calls. */
function mockTexture(w, h) {
  return {
    source: [{ width: w, height: h }],
    customData: {},
    frames: {},
    add(name, _si, x, y, fw, fh) {
      if (name in this.frames) return null;
      const f = { name, x, y, w: fw, h: fh, customData: null };
      this.frames[name] = f;
      return f;
    },
  };
}

/** Read a JSON file, tolerating a UTF-8 BOM (defensive; generator writes BOM-less). */
function readJson(p) {
  return JSON.parse(fs.readFileSync(p, "utf8").replace(/^﻿/, ""));
}

let failures = 0;

for (const file of Object.keys(COUNTS)) {
  const data = readJson(path.join(OUT, file));
  const how = dispatch(data);

  if (how !== "JSONArray") {
    console.log(`FAIL ${file}: dispatch=${how} -> JSONHash parser would warn "missing 'frames' Object" and add ZERO frames`);
    failures++;
    continue;
  }

  const tex = mockTexture(2048, 2048);
  JSONArray(tex, 0, data);

  const names = Object.keys(tex.frames);
  const count = names.length - 1; // exclude __BASE

  if (count !== COUNTS[file]) {
    console.log(`FAIL ${file}: parsed ${count} frames, expected ${COUNTS[file]}`);
    failures++;
    continue;
  }

  const missing = SPOT[file].filter((n) => !tex.frames[n]);
  if (missing.length) {
    console.log(`FAIL ${file}: missing frames: ${missing.join(", ")}`);
    failures++;
    continue;
  }

  // Frame rects must match the manifest record.
  const manifest = readJson(path.join(OUT, "manifest.json"));
  const key = file.replace(".json", "");
  const mf = manifest.atlasFrames[key].frames;
  let rectMismatch = 0;
  for (const mfr of mf) {
    const parsed = tex.frames[mfr.name];
    if (!parsed || parsed.x !== mfr.x || parsed.y !== mfr.y || parsed.w !== mfr.w || parsed.h !== mfr.h) rectMismatch++;
  }
  if (rectMismatch) {
    console.log(`FAIL ${file}: ${rectMismatch} frame rects differ from manifest`);
    failures++;
    continue;
  }

  console.log(`PASS ${file}: dispatch=JSONArray, ${count} frames parsed, spot-checks OK, rects match manifest`);
}

// ------------------------------------------------------- Phase 6 shop atlases --
// Same Phaser 3.90 parser dispatch, but the geometry cross-check reads the
// dedicated shop-manifest.json (items, generated by scripts/measure-shop-assets.ps1).
const SHOP_COUNTS = {
  "shop-decor.json": 8,
  "shop-wall.json": 12,
  "shop-plants.json": 12,
  "shop-desk.json": 12,
};

const SHOP_SPOT = {
  "shop-decor.json": ["trophy", "rug-sage", "frame-abstract"],
  "shop-wall.json": ["art-mountain", "wall-sconce", "mail-sorter"],
  "shop-plants.json": ["plant-fiddle", "rug-runner", "boot-tray"],
  "shop-desk.json": ["loveseat", "radio", "desk-organizer"],
};

const shopManifest = readJson(path.join(OUT, "shop-manifest.json"));
const shopItemsById = new Map((shopManifest.items || []).map((item) => [item.id, item]));

for (const file of Object.keys(SHOP_COUNTS)) {
  const data = readJson(path.join(OUT, file));
  const how = dispatch(data);

  if (how !== "JSONArray") {
    console.log(`FAIL ${file}: dispatch=${how} -> JSONHash parser would add ZERO frames`);
    failures++;
    continue;
  }

  const tex = mockTexture(2048, 2048);
  JSONArray(tex, 0, data);

  const names = Object.keys(tex.frames);
  const count = names.length - 1; // exclude __BASE

  if (count !== SHOP_COUNTS[file]) {
    console.log(`FAIL ${file}: parsed ${count} frames, expected ${SHOP_COUNTS[file]}`);
    failures++;
    continue;
  }

  const missing = SHOP_SPOT[file].filter((n) => !tex.frames[n]);
  if (missing.length) {
    console.log(`FAIL ${file}: missing frames: ${missing.join(", ")}`);
    failures++;
    continue;
  }

  let rectMismatch = 0;
  for (const name of names) {
    if (name === "__BASE") continue;
    const item = shopItemsById.get(name);
    const parsed = tex.frames[name];
    if (!item || parsed.x !== item.x || parsed.y !== item.y || parsed.w !== item.w || parsed.h !== item.h) {
      rectMismatch++;
    }
  }
  if (rectMismatch) {
    console.log(`FAIL ${file}: ${rectMismatch} frame rects differ from shop-manifest.json`);
    failures++;
    continue;
  }

  console.log(`PASS ${file}: dispatch=JSONArray, ${count} frames parsed, spot-checks OK, rects match shop-manifest`);
}

process.exit(failures ? 1 : 0);
